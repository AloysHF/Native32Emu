/// Render `text` into a transparent `width`x`height` ARGB image.
///
/// Unsupported characters are drawn as '?' so non-ASCII names still render
/// something recognizable instead of disappearing. When `centered` is set the
/// line is centered in the slot, otherwise it is left-aligned. Text that does
/// not fit is clipped to the slot.
pub fn render_text(text: &str, color: u32, width: u32, height: u32, centered: bool) -> RgbaImage {
    let mut pixels = vec![0u32; (width * height) as usize];
    let advance = GLYPH_WIDTH as i64;
    let glyphs: Vec<u8> = text
        .chars()
        .map(|c| {
            if (' '..='~').contains(&c) {
                c as u8
            } else {
                b'?'
            }
        })
        .collect();
    if glyphs.is_empty() || width == 0 || height == 0 {
        return RgbaImage {
            width,
            height,
            pixels,
        };
    }

    let line_width = glyphs.len() as i64 * advance;
    let mut x0 = if centered {
        (width as i64 - line_width) / 2
    } else {
        0
    };
    // Keep the start of an over-long line visible rather than clipping it away.
    x0 = x0.max(0);
    let y0 = (height as i64 - GLYPH_HEIGHT as i64) / 2;
    let ink = 0xFF00_0000 | (color & 0x00FF_FFFF);

    for (index, glyph) in glyphs.iter().enumerate() {
        let gx = x0 + index as i64 * advance;
        let rows = &GLYPHS[(glyph - 0x20) as usize];
        for (row, bits) in rows.iter().enumerate() {
            let y = y0 + row as i64;
            if y < 0 || y >= height as i64 {
                continue;
            }
            for col in 0..GLYPH_WIDTH as i64 {
                if bits & (1 << (GLYPH_WIDTH - 1 - col as u32)) == 0 {
                    continue;
                }
                let x = gx + col;
                if x < 0 || x >= width as i64 {
                    continue;
                }
                pixels[(y as u32 * width + x as u32) as usize] = ink;
            }
        }
    }

    RgbaImage {
        width,
        height,
        pixels,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ink_pixels(img: &RgbaImage) -> usize {
        img.pixels.iter().filter(|p| **p != 0).count()
    }

    fn first_ink_column(img: &RgbaImage) -> usize {
        img.pixels
            .iter()
            .enumerate()
            .find(|(_, p)| **p != 0)
            .map(|(i, _)| i % img.width as usize)
            .unwrap_or(usize::MAX)
    }

    #[test]
    fn empty_text_is_transparent() {
        let img = render_text("", 0x00FF_FFFF, 98, 16, false);
        assert_eq!((img.width, img.height), (98, 16));
        assert_eq!(ink_pixels(&img), 0);
    }

    #[test]
    fn glyphs_are_drawn_in_the_configured_color() {
        let img = render_text("A", 0x0012_34AB, 98, 16, false);
        let ink = img.pixels.iter().find(|p| **p != 0).unwrap();
        assert_eq!(*ink, 0xFF12_34AB);
    }

    #[test]
    fn unsupported_characters_fall_back_to_question_mark() {
        let fallback = render_text("?", 0x00FF_FFFF, 98, 16, false);
        let rendered = render_text("\u{2160}", 0x00FF_FFFF, 98, 16, false);
        assert_eq!(rendered.pixels, fallback.pixels);
    }

    #[test]
    fn centering_moves_the_line_right() {
        let left = render_text("Hi", 0x00FF_FFFF, 98, 16, false);
        let center = render_text("Hi", 0x00FF_FFFF, 98, 16, true);
        assert!(first_ink_column(&center) > first_ink_column(&left));
    }

    #[test]
    fn over_long_lines_are_clipped_but_start_visible() {
        let img = render_text("0123456789ABCDEFGHIJ", 0x00FF_FFFF, 98, 16, false);
        assert!(first_ink_column(&img) < 98);
        assert!(ink_pixels(&img) > 0);
    }
}
